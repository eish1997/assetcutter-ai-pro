/**
 * 从代号库中随机取一个作为组名称（角标显示为「代号 + 数量」）。
 * 传入已使用的名称集合时可查重，避免与现有组同名；若库内名称均被占用则自动加数字后缀（如「虚无 · 2」）。
 */
export function getRandomGroupCodeName(used?: Set<string>): string {
  const usedSet = used ?? new Set<string>();
  const maxTries = Math.min(GROUP_CODE_NAMES.length * 2, 100);
  for (let t = 0; t < maxTries; t++) {
    const i = Math.floor(Math.random() * GROUP_CODE_NAMES.length);
    const name = GROUP_CODE_NAMES[i];
    if (!usedSet.has(name)) return name;
  }
  const base = GROUP_CODE_NAMES[Math.floor(Math.random() * GROUP_CODE_NAMES.length)];
  let n = 2;
  while (usedSet.has(`${base} · ${n}`)) n++;
  return `${base} · ${n}`;
}
